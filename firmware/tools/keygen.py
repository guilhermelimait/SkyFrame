"""Creates the firmware signing key (once) and writes its public half into src/ota_pubkey.h.

Run with PlatformIO's Python (it has the 'cryptography' package):
    %USERPROFILE%\\.platformio\\penv\\Scripts\\python.exe tools\\keygen.py

The private key is SECRET: anyone who has it can sign firmware your display will accept.
It is created outside the repository (skyframe-keys/ next to it). Back it up and never upload it.
"""
import os, sys
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The private key lives OUTSIDE the repository so it can never be uploaded by accident:
#   <folder containing skyframe>/skyframe-keys/ota_signing_key.pem
# or wherever the SKYFRAME_SIGNING_KEY environment variable points.
key_path = os.environ.get("SKYFRAME_SIGNING_KEY") or os.path.join(os.path.dirname(os.path.dirname(root)), "skyframe-keys", "ota_signing_key.pem")
hdr_path = os.path.join(root, "src", "ota_pubkey.h")

if os.path.exists(key_path):
    key = serialization.load_pem_private_key(open(key_path, "rb").read(), password=None)
    print("using existing key", key_path)
else:
    os.makedirs(os.path.dirname(key_path), exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    with open(key_path, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    print("created new signing key", key_path)

pub = key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo).decode()
with open(hdr_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n// generated by tools/keygen.py: public key that firmware updates must be signed with\n")
    f.write("static const char OTA_PUBKEY_PEM[] =\n")
    for line in pub.strip().splitlines():
        f.write(f'  "{line}\\n"\n')
    f.write(";\n")
print("wrote", hdr_path)
