# Builds src/land_dots.h: a dotted world map (lat/lon of land points every ~3 degrees) for the ISS globe.
import json, math
topo = json.load(open("tools/land-110m.json"))
sx, sy = topo["transform"]["scale"]; tx, ty = topo["transform"]["translate"]
arcs = []
for a in topo["arcs"]:
    x = y = 0; pts = []
    for dx, dy in a:
        x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)
arc = lambda i: arcs[i] if i >= 0 else arcs[~i][::-1]
def ring(ids):
    out = []
    for k, i in enumerate(ids):
        a = arc(i); out += a if k == 0 else a[1:]
    return out
rings = []
def walk(g):
    t = g["type"]
    if t == "GeometryCollection": [walk(x) for x in g["geometries"]]
    elif t == "Polygon": [rings.append(ring(r)) for r in g["arcs"]]
    elif t == "MultiPolygon": [rings.append(ring(r)) for p in g["arcs"] for r in p]
walk(topo["objects"]["land"])
boxes = [(r, min(p[0] for p in r), max(p[0] for p in r), min(p[1] for p in r), max(p[1] for p in r)) for r in rings]
dots = []
la = -84
while la <= 84:
    step = 3 / max(.2, math.cos(math.radians(la)))
    lo = -180.0
    while lo < 180:
        inside = False
        for r, x0, x1, y0, y1 in boxes:
            if lo < x0 or lo > x1 or la < y0 or la > y1: continue
            j = len(r) - 1
            for i in range(len(r)):
                xi, yi = r[i]; xj, yj = r[j]
                if (yi > la) != (yj > la) and lo < (xj - xi) * (la - yi) / (yj - yi) + xi: inside = not inside
                j = i
        if inside: dots.append((la, lo))
        lo += step
    la += 3
with open("src/land_dots.h", "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n#include <stdint.h>\n"
            "// generated by tools/make_land.py from world-atlas land-110m (ISC, (c) Michael Bostock; data: Natural Earth)\n"
            "// lat, lon in 1/100 degree\n")
    f.write(f"static const int16_t LAND_DOTS[{len(dots)}][2] = {{\n")
    for i in range(0, len(dots), 8):
        f.write("  " + ", ".join(f"{{{round(a*100)},{round(b*100)}}}" for a, b in dots[i:i+8]) + ",\n")
    f.write("};\n")
print(len(dots), "land dots")
